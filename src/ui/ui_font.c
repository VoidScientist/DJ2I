/* =========================================================================
 * Fonctions internes
 * ========================================================================= */

/**
 * @brief Retourne le pointeur vers les données d'un glyphe.
 *
 * Si le caractère est hors de la plage imprimable, le glyphe '?' est retourné.
 *
 * @param c Caractère ASCII.
 * @return  Pointeur vers les 8 octets décrivant le glyphe.
 */
static const unsigned char *s_getGlyph(char c)
{
    unsigned char uc = (unsigned char)c;
    if (uc < 0x20 || uc > 0x7E) {
        uc = '?';
    }
    return s_font[uc - 0x20];
}

/* =========================================================================
 * API publique
 * ========================================================================= */

void uiFont_drawChar(uiContext_t *ctx, char c, int x, int y, int scale)
{
    const unsigned char *glyph = s_getGlyph(c);
    int row, col;

    for (row = 0; row < UI_FONT_CHAR_H; row++) {
        unsigned char line = glyph[row];
        for (col = 0; col < UI_FONT_CHAR_W; col++) {
            if (line & (0x80u >> col)) {
                SDL_Rect pixel = {
                    x + col * scale,
                    y + row * scale,
                    scale,
                    scale
                };
                SDL_RenderFillRect(ctx->renderer, &pixel);
            }
        }
    }
}

void uiFont_drawText(uiContext_t *ctx, const char *text,
                     int x, int y, int scale)
{
    if (!text) return;
    int cx = x;
    while (*text) {
        uiFont_drawChar(ctx, *text, cx, y, scale);
        cx += UI_FONT_CHAR_W * scale;
        text++;
    }
}

int uiFont_textWidth(const char *text, int scale)
{
    if (!text) return 0;
    return (int)strlen(text) * UI_FONT_CHAR_W * scale;
}

void uiFont_drawTextCentered(uiContext_t *ctx, const char *text,
                              int x, int y, int w, int scale)
{
    if (!text) return;
    int tw = uiFont_textWidth(text, scale);
    int ox = x + (w - tw) / 2;
    uiFont_drawText(ctx, text, ox, y, scale);
}
